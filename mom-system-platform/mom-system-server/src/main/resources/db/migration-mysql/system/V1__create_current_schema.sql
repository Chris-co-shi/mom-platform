CREATE TABLE mom_inbox_event (
    event_id varchar(64) NOT NULL COMMENT '生产方事件全局唯一标识',
    consumer_name varchar(160) NOT NULL COMMENT '稳定消费者名称和幂等空间',
    event_type varchar(160) NOT NULL,
    event_version int NOT NULL,
    correlation_id varchar(128) NOT NULL COMMENT '端到端关联标识',
    received_at datetime(6) NOT NULL,
    processed_at datetime(6) COMMENT '消费者业务动作成功完成时间',
    created_at datetime(6) NOT NULL,
    CONSTRAINT ck_mom_inbox_event_version_positive CHECK ((event_version > 0)),
    CONSTRAINT pk_mom_inbox_event PRIMARY KEY (event_id, consumer_name),
    KEY ix_mom_inbox_event_processed_at (processed_at, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='System 运行时变更事件消费幂等 Inbox';

CREATE TABLE mom_outbox_event (
    event_id varchar(64) NOT NULL COMMENT '事件全局唯一标识，重试时保持不变',
    event_type varchar(160) NOT NULL,
    event_version int NOT NULL,
    aggregate_type varchar(100) NOT NULL,
    aggregate_id varchar(128) NOT NULL COMMENT '产生事件的聚合技术标识',
    occurred_at datetime(6) NOT NULL,
    producer varchar(100) NOT NULL,
    correlation_id varchar(128) NOT NULL COMMENT '端到端关联标识',
    payload_json text NOT NULL COMMENT '版本化且不含 Secret 的事件 JSON 负载',
    status varchar(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/CLAIMED/RETRY/SENT/DEAD 发布状态',
    retry_count int NOT NULL DEFAULT 0,
    next_attempt_at datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    lease_owner varchar(200),
    lease_until datetime(6),
    sent_at datetime(6),
    last_error varchar(1000),
    created_at datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT ck_mom_outbox_event_retry_count_non_negative CHECK ((retry_count >= 0)),
    CONSTRAINT ck_mom_outbox_event_status_allowed CHECK (((status) IN ('PENDING', 'CLAIMED', 'RETRY', 'SENT', 'DEAD'))),
    CONSTRAINT ck_mom_outbox_event_version_positive CHECK ((event_version > 0)),
    CONSTRAINT pk_mom_outbox_event PRIMARY KEY (event_id),
    KEY ix_mom_outbox_event_claim (status, next_attempt_at, lease_until, occurred_at, event_id),
    KEY ix_mom_outbox_event_sent_at (sent_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='System 运行时变更事件可靠发布 Outbox';

